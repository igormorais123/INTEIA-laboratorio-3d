import {MeshoptDecoder} from 'three/addons/libs/meshopt_decoder.module.js';
import fs from 'node:fs';
import * as THREE from 'three';
import {GLTFLoader} from 'three/addons/loaders/GLTFLoader.js';
const b=fs.readFileSync('assets/power-unit-v1.glb'),len=b.readUInt32LE(12),j=JSON.parse(b.subarray(20,20+len));
j.materials=[{}];delete j.images;delete j.textures;delete j.samplers;j.extensionsUsed=['EXT_meshopt_compression','KHR_mesh_quantization'];j.extensionsRequired=['EXT_meshopt_compression','KHR_mesh_quantization'];j.meshes.forEach(m=>m.primitives.forEach(p=>p.material=0));
const json=Buffer.from(JSON.stringify(j)),pad=Buffer.alloc(Math.ceil(json.length/4)*4,32);json.copy(pad);const tail=b.subarray(20+len),out=Buffer.alloc(20+pad.length+tail.length);b.copy(out,0,0,12);out.writeUInt32LE(out.length,8);out.writeUInt32LE(pad.length,12);out.writeUInt32LE(0x4e4f534a,16);pad.copy(out,20);tail.copy(out,20+pad.length);
const g=await new GLTFLoader().setMeshoptDecoder(MeshoptDecoder).parseAsync(out.buffer.slice(out.byteOffset,out.byteOffset+out.length),'');
const unit=g.scene;
if(g.animations.length!==1||g.animations[0].tracks.length!==19)throw Error('Motor sem os 19 canais de movimento esperados');
const assemblies=[];unit.traverse(o=>{if(o.name.startsWith('assembly_'))assemblies.push(o);});
if(assemblies.length<5)throw Error('Grupos do motor ausentes');
const mixer=new THREE.AnimationMixer(unit);mixer.clipAction(g.animations[0]).play();mixer.setTime(0);unit.updateMatrixWorld(true);
const before=new Map();unit.traverse(o=>before.set(o.uuid,o.matrixWorld.clone()));
mixer.setTime(.71);unit.updateMatrixWorld(true);let moved=0;
unit.traverse(o=>{if(o.matrixWorld.elements.some((v,i)=>Math.abs(v-before.get(o.uuid).elements[i])>1e-6))moved++;});
if(!moved)throw Error('Motor nao anima');
for(let cycle=1;cycle<=20;cycle++)mixer.setTime(cycle*g.animations[0].duration);
unit.updateMatrixWorld(true);let drift=0;
unit.traverse(o=>{drift=Math.max(drift,...o.matrixWorld.elements.map((v,i)=>Math.abs(v-before.get(o.uuid).elements[i])));});
if(drift>1e-5)throw Error('Deriva no motor: '+drift);
console.log({motor:'V6 ilustrativo INTEIA',assemblies:assemblies.length,animationChannels:19,movingNodes:moved,cycles:20,drift,passed:true});
